-- ---------- 11 · verifikasi ----------
DO $$ DECLARE
  n_fleet int; n_msn int; n_par int; n_ins int;
BEGIN
  SELECT count(*) INTO n_fleet FROM fleet.info WHERE vessel_type = 'SURVEY';
  SELECT count(*) INTO n_msn FROM survey.mission;
  SELECT count(*) INTO n_par FROM param.system_parameter WHERE param_key LIKE 'mission_%';
  SELECT count(*) INTO n_ins FROM survey.instrument;
  IF n_fleet < 1 THEN
    RAISE EXCEPTION 'VERIFIKASI GAGAL: kapal SURVEY (SV01) tidak terdaftar';
  END IF;
  IF n_msn <> 0 THEN
    RAISE NOTICE 'survey.mision sudah berisi % baris (re-run DDL — cut-off §8 hanya utk instalasi pertama)', n_msn;
  END IF;
  IF n_par < 7 THEN
    RAISE EXCEPTION 'VERIFIKASI GAGAL: parameter mission_* kurang (%)', n_par;
  END IF;
  IF n_ins < 3 THEN
    RAISE EXCEPTION 'VERIFIKASI GAGAL: seed instrument kurang (%)', n_ins;
  END IF;
  -- kolom kunci ada & tipe benar (guard double-run)
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema='survey' AND table_name='mission'
                    AND column_name='mon_wo_id' AND data_type='bigint') THEN
    RAISE EXCEPTION 'VERIFIKASI GAGAL: survey.mission.mon_wo_id tidak terbentuk';
  END IF;
  RAISE NOTICE 'DDL 14 OK: SV01 terdaftar · % tabel survey baru · % parameter · % instrument',
    (SELECT count(*) FROM pg_tables WHERE schemaname='survey' AND tablename LIKE 'mission_%'), n_par, n_ins;
END $$;

