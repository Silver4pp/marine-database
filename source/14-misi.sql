-- ---------- 2 · survey.mission — 1 baris = 1 misi (FR-4-06) ----------
CREATE TABLE IF NOT EXISTS survey.mission (
  mission_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_no    varchar(60)  NOT NULL UNIQUE,              -- MSV/[LOKASI]/[YYMM]/[URUT] (FR-4-17)
  fleet_code    varchar(30)  NOT NULL REFERENCES fleet.info(fleet_code),
  mission_kind  varchar(12)  NOT NULL,                     -- BATHY/SAMP/ENV/BUOY · ANGKUT/MAINT/PATROLI (param)
  target_type   varchar(12)  NOT NULL,                     -- ZONE/WORK_AREA/STATION/KOORDINAT (FR-4-03)
  target_code   varchar(40),
  lat           double precision,
  lng           double precision,
  purpose       text,
  planned_start timestamptz NOT NULL,
  planned_end   timestamptz NOT NULL,
  ts_departed   timestamptz,                               -- BERANGKAT
  ts_returned   timestamptz,                               -- PULANG
  engine_hours  numeric(10,2),                             -- jam kerja mesin (log)
  status        varchar(12)  NOT NULL DEFAULT 'RENCANA',
  leader_name   varchar(150),
  crew          jsonb        NOT NULL DEFAULT '[]'::jsonb, -- [{nama, peran, sertifikasi?}]
  mon_wo_id     bigint REFERENCES enviro.mon_work_order(wo_id),   -- FR-4-11 nullable
  is_locked     boolean      NOT NULL DEFAULT false,       -- terkunci saat SELESAI (FR-4-18)
  tenant_id     uuid,
  created_at    timestamptz  NOT NULL DEFAULT now(),
  updated_at    timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_msn_kind   CHECK (mission_kind IN ('BATHY','SAMP','ENV','BUOY',
                                                   'ANGKUT','MAINT','PATROLI')),
  CONSTRAINT chk_msn_target CHECK (target_type IN ('ZONE','WORK_AREA','STATION','KOORDINAT')),
  CONSTRAINT chk_msn_status CHECK (status IN ('RENCANA','DISETUJUI','BERANGKAT','DI LAUT',
                                              'PULANG','LAPORAN','SELESAI','DITOLAK','BATAL')),
  CONSTRAINT chk_msn_jendela CHECK (planned_end > planned_start),
  CONSTRAINT chk_msn_koordinat CHECK (target_type <> 'KOORDINAT' OR (lat IS NOT NULL AND lng IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_msn_status  ON survey.mission(status);
CREATE INDEX IF NOT EXISTS idx_msn_jendela ON survey.mission(fleet_code, planned_start);
CREATE INDEX IF NOT EXISTS idx_msn_wo      ON survey.mission(mon_wo_id);

-- ---------- 3 · survey.mission_check — checklist kelayakan pra-berangkat (FR-4-09) ----------
-- pola trip_doc_check feat-v7: 1 baris per (misi, item) — item_key dari parameter
-- mission_check_wajib (CUACA/PPE/KOMUNIKASI/ABK/ALAT); status OK/TIDAK + siapa/kapan.
CREATE TABLE IF NOT EXISTS survey.mission_check (
  check_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id   bigint       NOT NULL REFERENCES survey.mission(mission_id) ON DELETE CASCADE,
  item_key     varchar(20)  NOT NULL,
  status       varchar(8)   NOT NULL DEFAULT 'TIDAK',      -- OK / TIDAK
  catatan      text,
  verified_by  varchar(150),
  verified_at  timestamptz,
  created_at   timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_mck_status CHECK (status IN ('OK','TIDAK')),
  CONSTRAINT uq_mck UNIQUE (mission_id, item_key)
);

-- ---------- 4 · survey.mission_log — log eksekusi terstruktur (FR-4-12) ----------
CREATE TABLE IF NOT EXISTS survey.mission_log (
  log_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id   bigint       NOT NULL REFERENCES survey.mission(mission_id) ON DELETE CASCADE,
  logged_at    timestamptz  NOT NULL DEFAULT now(),
  log_type     varchar(12)  NOT NULL,                      -- KEGIATAN/CUACA/HAMBATAN/NARATIF
  payload      jsonb        NOT NULL DEFAULT '{}'::jsonb,  -- terstruktur per jenis
  created_by   varchar(150),
  created_at   timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_mlg_type CHECK (log_type IN ('KEGIATAN','CUACA','HAMBATAN','NARATIF'))
);
CREATE INDEX IF NOT EXISTS idx_mlg_mission ON survey.mission_log(mission_id, logged_at);

-- ---------- 5 · survey.instrument — master alat survei + kalibrasi inline (FR-4-05, §9-8) ----------
-- hse.certificate terikat fleet_code NOT NULL (khusus kapal) sehingga TIDAK dipakai.
CREATE TABLE IF NOT EXISTS survey.instrument (
  instrument_code varchar(30)  PRIMARY KEY,
  nama            varchar(150) NOT NULL,
  tipe            varchar(20)  NOT NULL DEFAULT 'LAIN',    -- ECHOSOUNDER/GPS/SONDE/LAIN
  status          varchar(20)  NOT NULL DEFAULT 'AKTIF',
  cert_no         varchar(60),                             -- kalibrasi inline
  issuer          varchar(120),
  issued_at       date,
  expires_at      date,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_ins_tipe  CHECK (tipe IN ('ECHOSOUNDER','GPS','SONDE','LAIN')),
  CONSTRAINT chk_ins_status CHECK (status IN ('AKTIF','PERBAIKAN','KELUAR'))
);

-- ---------- 6 · survey.mission_result — hasil per misi (FR-4-15) ----------
CREATE TABLE IF NOT EXISTS survey.mission_result (
  result_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id     bigint      NOT NULL REFERENCES survey.mission(mission_id) ON DELETE CASCADE,
  kind           varchar(12) NOT NULL,                     -- ikut mission_kind
  summary        jsonb       NOT NULL DEFAULT '{}'::jsonb, -- BATHY: luas/volume/kedalaman ·
                                                           -- SAMP: titik+hasil uji · ENV: parameter ·
                                                           -- BUOY: catatan unduhan · DUKUNGAN: naratif
  station_code   varchar(30) REFERENCES enviro.station(station_code),
  doc_ref        bigint      REFERENCES document.document(document_id),  -- file hasil (FR-4-16)
  instrument_code varchar(30) REFERENCES survey.instrument(instrument_code),
  created_by     varchar(150),
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_mrs_kind CHECK (kind IN ('BATHY','SAMP','ENV','BUOY',
                                         'ANGKUT','MAINT','PATROLI'))
);
CREATE INDEX IF NOT EXISTS idx_mrs_mission ON survey.mission_result(mission_id);

-- ---------- 7 · survey.mission_cost — biaya misi, TERPISAH dari produksi (FR-4-19/20, §9-4) ----------
CREATE TABLE IF NOT EXISTS survey.mission_cost (
  cost_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id   bigint       NOT NULL REFERENCES survey.mission(mission_id) ON DELETE CASCADE,
  category     varchar(12)  NOT NULL,                      -- BBM/CREW/LOGISTIK/LAIN
  amount       numeric(16,2) NOT NULL CHECK (amount >= 0),
  qty_liter    numeric(12,2),                              -- khusus BBM
  engine_meter numeric(12,2),                              -- jam-meter mesin (BBM)
  source       varchar(12)  NOT NULL DEFAULT 'MANUAL',     -- MANUAL (input) — otomatis menyusul
  description  text,
  created_by   varchar(150),
  created_at   timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT chk_mcs_cat CHECK (category IN ('BBM','CREW','LOGISTIK','LAIN'))
);
CREATE INDEX IF NOT EXISTS idx_mcs_mission ON survey.mission_cost(mission_id);

