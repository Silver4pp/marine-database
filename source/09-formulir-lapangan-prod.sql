-- Metadata lampiran foto formulir lapangan (5 jenis: draft survey, BAP,
-- inspeksi HSE, toolbox meeting, monitoring enviro).
--   · Foto TIDAK disimpan di filesystem container (ter-reset saat deploy).
--   · PROD: Supabase Storage via REST (env SUPABASE_URL + SERVICE_KEY +
--     SUPABASE_BUCKET_FOTO default 'erp-form-foto') — DB hanya metadata
--     (kolom data NULL).
--   · DEV fallback (tanpa env Supabase): bytea TERKOMPRESI di kolom data
--     (sisi panjang ≤1600 px, ≤1 MB, EXIF dibuang) supaya tetap teruji.
-- Idempoten — aman dijalankan berulang.
-- Pemakaian PROD (Supabase): psql "$DATABASE_URL" -f 09-formulir-lapangan-prod.sql
-- Pemakaian DEV          : sudo -u postgres psql -d uat_pasir_laut -f /tmp/09.sql
-- ============================================================================

CREATE TABLE IF NOT EXISTS document.form_foto (
    foto_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_jenis    varchar(20)  NOT NULL
                  CONSTRAINT form_foto_jenis_check CHECK (form_jenis IN
                  ('DRAFT_SURVEY', 'BAP', 'INSPEKSI_HSE', 'TOOLBOX', 'MONITORING_ENVIRO')),
    record_id     bigint       NOT NULL,   -- trip_id | bap_id | inspection_id | ttm_id | mon_report_id
    record_label  varchar(60)  NOT NULL,   -- utk galeri (TRIP-907 · BAP-2026-0087 · dst.)
    file_path     varchar(200) NOT NULL,   -- path Supabase / 'bytea:<id>' (fallback dev)
    storage       varchar(10)  NOT NULL
                  CONSTRAINT form_foto_storage_check CHECK (storage IN ('SUPABASE', 'DB')),
    ukuran        integer      NOT NULL,   -- bytes SETELAH kompres (≤1 MB)
    lebar         integer,
    tinggi        integer,
    data          bytea,                   -- hanya fallback dev; PROD selalu NULL
    diunggah_oleh varchar(30)  NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_form_foto_record
    ON document.form_foto (form_jenis, record_id);
CREATE INDEX IF NOT EXISTS idx_form_foto_waktu
    ON document.form_foto (created_at DESC);
